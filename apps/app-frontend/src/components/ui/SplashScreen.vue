<template>
	<Transition name="splash-fade" @after-leave="onAfterLeave">
		<div v-if="!doneLoading" class="splash-screen" :class="`${theme.active}-mode`">
			<div class="app-logo-wrapper" data-tauri-drag-region>
				<div class="flex items-center gap-3 select-none" data-tauri-drag-region>
					<SolaraIcon class="size-12 shrink-0" />
					<span class="text-3xl font-extrabold tracking-tight text-contrast">Solara Launcher</span>
				</div>
				<ProgressBar class="loading-bar" :progress="progress" />
				<span v-if="message" class="text-secondary">{{ message }}</span>
			</div>
			<div class="gradient-bg" data-tauri-drag-region></div>
			<div class="cube-bg"></div>
			<div class="base-bg"></div>
		</div>
	</Transition>
</template>

<script setup>
import { SolaraIcon } from '@modrinth/assets'
import { defineMessages, injectLoadingState, useVIntl } from '@modrinth/ui'
import { computed, onMounted, ref, watch } from 'vue'

import ProgressBar from '@/components/ui/ProgressBar.vue'
import { useAppEvent } from '@/composables/use-app-event'
import { useTheme } from '@/composables/use-theme.ts'
import { debugStartup } from '@/helpers/startup-debug'

const theme = useTheme()
const { formatMessage } = useVIntl()

const messages = defineMessages({
	movingAppDirectory: {
		id: 'app.splash.moving-app-directory',
		defaultMessage: 'Moving your app directory...',
	},
})

const doneLoading = ref(false)
const loadingProgress = ref(0)
const directoryMoveFraction = ref(null)

const progress = computed(() =>
	directoryMoveFraction.value === null
		? Math.min(loadingProgress.value, 100)
		: directoryMoveFraction.value * 100,
)
const message = computed(() =>
	directoryMoveFraction.value === null ? null : formatMessage(messages.movingAppDirectory),
)

const MIN_DISPLAY_MS = 500
const mountedAt = Date.now()

const loading = injectLoadingState()
onMounted(() => debugStartup('Splash mounted'))

function onAfterLeave() {
	debugStartup('Splash fade completed', { displayedMs: Date.now() - mountedAt })
	loading.setEnabled(true)
}

watch(
	[loading.barEnabled, loading.pending],
	([barEnabled, pending]) => {
		debugStartup('Splash loading state changed', { barEnabled, pending })
		if (barEnabled) {
			return
		}

		if (pending) {
			loadingProgress.value = 0
			fakeLoadingIncrease()
			return
		}

		const elapsed = Date.now() - mountedAt
		const delay = Math.max(0, MIN_DISPLAY_MS - elapsed)
		debugStartup('Splash dismissal scheduled', { delayMs: delay, displayedMs: elapsed })

		setTimeout(() => {
			if (loading.pending.value) {
				debugStartup('Splash dismissal deferred: new loading work')
				return
			}
			doneLoading.value = true
			debugStartup('Splash fade started', { displayedMs: Date.now() - mountedAt })
		}, delay)
	},
	{ immediate: true },
)

function fakeLoadingIncrease() {
	if (loadingProgress.value < 95) {
		setTimeout(() => {
			loadingProgress.value += 2
			fakeLoadingIncrease()
		}, 5)
	}
}

useAppEvent('loading', (e) => {
	if (e.event.type === 'directory_move') {
		directoryMoveFraction.value = e.fraction ?? null
	}
})
</script>

